def nvrtc_compile_to_cubin(
    src: str,
    opts: list[str],
    name: str,
    headers: dict[str, str] | None = None,
) -> tuple[bytes, bytes]:
    """
    Compile CUDA C source to CUBIN using NVRTC.

    Args:
        src: CUDA C source code
        opts: Compiler options (e.g., ["--gpu-architecture=sm_89"])
        name: Kernel name expression to lower and resolve
        headers: Optional dict mapping header names to their source content.
                 Enables #include "name" without filesystem access.
    """
    if headers:
        header_names = [n.encode() for n in headers]
        header_srcs = [s.encode() for s in headers.values()]
        num_headers = len(headers)
    else:
        header_names, header_srcs, num_headers = None, None, 0

    prog = _check(_nvrtc.nvrtcCreateProgram(src.encode(), b"kernel.cu", num_headers, header_srcs, header_names))

    c_opts = [o.encode() for o in opts]
    compile_error: RuntimeError | None = None
    try:
        _check(_nvrtc.nvrtcAddNameExpression(prog, name.encode()))
        _check(_nvrtc.nvrtcCompileProgram(prog, len(c_opts), c_opts))
        lowered_name = _check(_nvrtc.nvrtcGetLoweredName(prog, name.encode()))
        cubin_size = _check(_nvrtc.nvrtcGetCUBINSize(prog))
        cubin = bytearray(cubin_size)
        _check(_nvrtc.nvrtcGetCUBIN(prog, cubin))
        return bytes(cubin), lowered_name
    except RuntimeError as e:
        compile_error = e
        log_size = _check(_nvrtc.nvrtcGetProgramLogSize(prog))
        log = bytearray(log_size)
        _check(_nvrtc.nvrtcGetProgramLog(prog, log))
        raise RuntimeError(f"{e}\nNVRTC compilation log:\n{log.decode()}") from e
    finally:
        try:
            _check(_nvrtc.nvrtcDestroyProgram(prog))
        except RuntimeError:
            if compile_error is None:
                raise



def make_kernel_node_params(
    func: Any,
    grid: tuple[int, ...],
    block: tuple[int, ...],
    args: list[Any],
    shared_mem: int = 0,
) -> tuple[Any, Any]:
    """Build a ``CUDA_KERNEL_NODE_PARAMS`` for graph node creation/update.

    Returns ``(params, refs)`` — *refs* must be kept alive to prevent GC
    of the internal pointer array that ``params.kernelParams`` references.

    After mutating ``args[i].value`` in-place, the same *params* struct
    picks up the new values through the pointer chain — just pass it to
    ``graph_exec_kernel_node_set_params`` again.
    """
    KNP = _drv.CUDA_KERNEL_NODE_PARAMS
    gx, gy, gz = (*grid, 1, 1, 1)[:3]
    bx, by, bz = (*block, 1, 1, 1)[:3]

    # Build kernelParams void** (same layout as launch_kernel).
    param_array = (c_void_p * len(args))()
    for i, w in enumerate(args):
        param_array[i] = addressof(w)

    params = KNP()
    params.func = func
    params.gridDimX = gx
    params.gridDimY = gy
    params.gridDimZ = gz
    params.blockDimX = bx
    params.blockDimY = by
    params.blockDimZ = bz
    params.sharedMemBytes = shared_mem
    params.kernelParams = addressof(param_array)
    params.extra = 0
    return params, param_array


_CU_MEMORYTYPE_HOST = _drv.CUmemorytype.CU_MEMORYTYPE_HOST
_CU_MEMORYTYPE_DEVICE = _drv.CUmemorytype.CU_MEMORYTYPE_DEVICE


def _make_memcpy_params(dst: int, nbytes: int) -> Any:
    """Build base ``CUDA_MEMCPY3D`` with common destination/dimension fields."""
    params = _drv.CUDA_MEMCPY3D()
    params.srcPitch = nbytes
    params.srcHeight = 1
    params.dstMemoryType = _CU_MEMORYTYPE_DEVICE
    params.dstDevice = dst
    params.dstPitch = nbytes
    params.dstHeight = 1
    params.WidthInBytes = nbytes
    params.Height = 1
    params.Depth = 1
    return params


def make_memcpy_dtod_params(dst: int, src: int, nbytes: int) -> Any:
    """Build a ``CUDA_MEMCPY3D`` for a 1-D device-to-device copy."""
    params = _make_memcpy_params(dst, nbytes)
    params.srcMemoryType = _CU_MEMORYTYPE_DEVICE
    params.srcDevice = src
    return params


def make_memcpy_htod_params(dst: int, src_host: int, nbytes: int) -> Any:
    """Build a ``CUDA_MEMCPY3D`` for a 1-D host-to-device copy."""
    params = _make_memcpy_params(dst, nbytes)
    params.srcMemoryType = _CU_MEMORYTYPE_HOST
    params.srcHost = src_host
    return params


def launch_kernel(
    func: Any,
    grid: tuple[int, ...],
    block: tuple[int, ...],
    args: list[Any],
    stream: int,
    shared_mem_bytes: int = 0,
) -> None:
    gx, gy, gz = (*grid, 1, 1, 1)[:3]
    bx, by, bz = (*block, 1, 1, 1)[:3]

    param_array = (c_void_p * len(args))()
    for i, w in enumerate(args):
        param_array[i] = addressof(w)
    kernel_params = addressof(param_array)

    _check(_drv.cuLaunchKernel(func, gx, gy, gz, bx, by, bz, shared_mem_bytes, stream, kernel_params, 0))



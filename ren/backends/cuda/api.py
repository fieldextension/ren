def graph_instantiate(graph: Any, stream: int) -> Any:
    params = _drv.CUDA_GRAPH_INSTANTIATE_PARAMS()
    params.flags = _drv.CUgraphInstantiate_flags.CUDA_GRAPH_INSTANTIATE_FLAG_UPLOAD
    params.hUploadStream = stream
    try:
        return _check(_drv.cuGraphInstantiateWithParams(graph, params))
    except CUDAError as e:
        raise CUDAError(e.code, f"graph instantiate result {params.result_out}, error node {params.hErrNode_out}") from e



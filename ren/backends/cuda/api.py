def _err_string(code: Any) -> str:
    if isinstance(code, _drv.CUresult):
        err, name = _drv.cuGetErrorName(code)
        if err != _drv.CUresult.CUDA_SUCCESS:
            return "<unknown>"
        return name.decode() if isinstance(name, bytes) else name
    return str(code)


class CUDAError(RuntimeError):
    def __init__(self, code: Any, detail: str | None = None):
        self.code = code
        message = f"CUDA error {_err_string(code)}"
        super().__init__(f"{message}: {detail}" if detail else message)


@overload
def _check(res: tuple[Any, Any]) -> Any: ...


@overload
def _check(res: Any) -> Any: ...


def _check(res: Any) -> Any:
    if isinstance(res, tuple):
        code, *rest = res
    else:
        code, rest = res, []
    if isinstance(code, _drv.CUresult):
        if code != _drv.CUresult.CUDA_SUCCESS:
            raise CUDAError(code)
        return rest[0] if len(rest) == 1 else tuple(rest)
    if isinstance(code, _nvrtc.nvrtcResult):
        if code != _nvrtc.nvrtcResult.NVRTC_SUCCESS:
            try:
                msg = _nvrtc.nvrtcGetErrorString(code)
                if isinstance(msg, (bytes, bytearray)):
                    msg = msg.decode()
            except Exception:
                msg = str(code)
            raise RuntimeError(f"NVRTC error {code}: {msg}")
        return rest[0] if len(rest) == 1 else tuple(rest)
    if code not in (0, None):
        raise RuntimeError(f"Unknown CUDA/NVRTC status code {code}")
    return rest[0] if len(rest) == 1 else tuple(rest)


def _as_graph_node_array(nodes: list[Any] | tuple[Any, ...] | None) -> tuple[Any | None, int]:
    if not nodes:
        return None, 0
    return tuple(nodes), len(nodes)



def is_deviceptr(buf: Any) -> TypeGuard[CUdeviceptr]:
    return isinstance(buf, _drv.CUdeviceptr)


def deviceptr_offset(buf: Any, offset: int) -> Any:
    """Create an offset device pointer from an existing CUdeviceptr."""
    assert is_deviceptr(buf), f"expected CUdeviceptr, got {type(buf)}"
    base_val: int = int(buf)
    return _drv.CUdeviceptr(base_val + offset)


